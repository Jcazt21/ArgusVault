/// Clear our copy from the clipboard if it is still there, then either retry shortly (the
/// clipboard was busy) or stop the timer. Returns a status line for the UI.
fn clear_now(weak: &slint::Weak<MainWindow>) -> &'static str {
    let ticket = CLIPBOARD.with(|c| c.borrow_mut().ticket.take());
    let Some(ticket) = ticket else {
        CLIPBOARD.with(|c| c.borrow().timer.stop());
        return "";
    };
    if let Ok(cleared) = clipboard::clear_if_unchanged(ticket) {
        CLIPBOARD.with(|c| c.borrow().timer.stop());
        // `false` means something else was copied meanwhile: it is left alone.
        if cleared {
            "Clipboard cleared."
        } else {
            ""
        }
    } else {
        CLIPBOARD.with(|c| c.borrow_mut().ticket = Some(ticket));
        schedule_clear(weak, CLEAR_RETRY_SECS);
        "Could not clear the clipboard yet; retrying."
    }
}

fn schedule_clear(weak: &slint::Weak<MainWindow>, secs: u64) {
    CLIPBOARD.with(|c| {
        c.borrow().timer.start(TimerMode::SingleShot, Duration::from_secs(secs), {
            let weak = weak.clone();
            move || {
                let message = clear_now(&weak);
                if let Some(ui) = weak.upgrade() {
                    ui.set_status(message.into());
                }
            }
        });
    });
}

/// Put `value` on the clipboard through the protected path (excluded from history and cloud sync,
/// cleared after the configured delay) and say so in the status line. Even non-secret values such
/// as a username or host go this way: there is no reason to leave them in history.
fn copy_text(ui: &MainWindow, value: &str, what: &str) {
    let secs = with_session(|s| s.vault.vault.settings.clipboard_clear_secs).unwrap_or(20);
    match clipboard::copy_secret(value) {
        Ok(ticket) => {
            CLIPBOARD.with(|c| c.borrow_mut().ticket = Some(ticket));
            schedule_clear(&ui.as_weak(), u64::from(secs));
            ui.set_status(format!("{what} copied. Clears in {secs} s.").into());
        }
        Err(e) => ui.set_status(format!("Could not copy: {e}.").into()),
    }
}

