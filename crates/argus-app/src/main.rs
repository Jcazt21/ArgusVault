/// Native handle of the window; `None` while it does not exist yet.
fn native_hwnd(ui: &MainWindow) -> Option<isize> {
    ui.window().window_handle().window_handle().ok().and_then(|h| match h.as_raw() {
        RawWindowHandle::Win32(w) => Some(w.hwnd.get()),
        _ => None,
    })
}

/// Which kind of file a dialog is for.
#[derive(Clone, Copy)]
enum Pick {
    Vault,
    Keyfile,
    Import,
}

impl Pick {
    fn title(self, saving: bool) -> &'static str {
        match (self, saving) {
            (Self::Vault, false) => "Open vault",
            (Self::Vault, true) => "Where to save the new vault",
            (Self::Keyfile, false) => "Choose a keyfile",
            (Self::Keyfile, true) => "Create a new keyfile",
            (Self::Import, _) => "Choose the file to import",
        }
    }

    fn filters(self) -> &'static [(&'static str, &'static str)] {
        match self {
            Self::Vault => &[("Argus vaults (*.argus)", "*.argus"), ("All files", "*.*")],
            Self::Keyfile => &[("Keyfiles (*.argkey)", "*.argkey"), ("All files", "*.*")],
            Self::Import => {
                &[("KeePass CSV or Bitwarden JSON", "*.csv;*.json"), ("All files", "*.*")]
            }
        }
    }

    fn extension(self) -> Option<&'static str> {
        match self {
            Self::Vault => Some("argus"),
            Self::Keyfile => Some(argus_core::keyfile::EXTENSION),
            Self::Import => None,
        }
    }
}

/// Show a file dialog. `Ok(None)` means the user cancelled.
fn pick_file(ui: &MainWindow, what: Pick, saving: bool) -> Result<Option<PathBuf>, PlatformError> {
    let request = dialog::Request {
        title: what.title(saving),
        filters: what.filters(),
        default_extension: if saving { what.extension() } else { None },
    };
    let owner = native_hwnd(ui).unwrap_or(0);
    if saving {
        dialog::save_file(owner, &request)
    } else {
        dialog::open_file(owner, &request)
    }
}

