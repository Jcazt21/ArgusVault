/// An unlocked vault plus the UI's view of it. Lives on the UI thread only.
struct Session {
    /// Distinguishes this unlock from a later one, so a slow background job started in one
    /// session never touches the next.
    id: u64,
    vault: UnlockedVault,
    /// Keeps other Argus Vault windows from opening (and overwriting) the same file. Released
    /// when the session is dropped, i.e. on lock.
    _instance: VaultLock,
    /// Keeps other programs from writing to, deleting or renaming the vault file while it is
    /// unlocked (they can still read it: it is encrypted). Released around every save and re-key,
    /// and retried by [`keep_file_protected`] if another program had the file open at that moment.
    file_lock: ExclusiveFileLock,
    /// The user has already been told the file is unprotected (once per episode).
    lock_warned: bool,
    /// Keyfile path used to unlock (not a secret); offered again when changing credentials.
    keyfile: String,
    /// Entry indices shown in the list, in display order.
    shown: Vec<usize>,
    /// Index (into the vault) of the entry open in the detail panel.
    selected: Option<usize>,
    /// Entry being edited in the editor, if it is editing rather than creating.
    editing: Option<EntryId>,
    query: String,
    filter: Option<EntryKind>,
    /// A background re-key is running: every other change to the vault is refused meanwhile, or
    /// it would be saved under the old key and overwrite the new file.
    rekeying: bool,
}

impl Session {
    /// Save the vault to disk. A save replaces the file by renaming a temporary file over it,
    /// which the file lock would block, so the lock is let go for the write and taken again after.
    ///
    /// The result is the result of the **save**, never of the re-lock: if another program happens
    /// to have the file open in that instant the lock stays released ([`keep_file_protected`]
    /// retries it), but the data is on disk and callers, which roll back memory on `Err`, must
    /// not be told otherwise.
    pub(crate) fn save(&mut self) -> Result<(), Error> {
        self.file_lock.release();
        let result = self.vault.save();
        let _ = self.file_lock.reacquire();
        result
    }

    /// Try to protect the vault file again if it is not. `Failed { first: true }` is the first
    /// failure of an episode, the one the user should be told about.
    fn retry_file_lock(&mut self) -> Relock {
        // Released on purpose while a re-key rewrites the file.
        if self.rekeying || self.file_lock.is_locked() {
            if self.file_lock.is_locked() {
                self.lock_warned = false;
            }
            return Relock::NotNeeded;
        }
        match self.file_lock.reacquire() {
            Ok(()) => {
                self.lock_warned = false;
                Relock::Restored
            }
            Err(_) => Relock::Failed { first: !std::mem::replace(&mut self.lock_warned, true) },
        }
    }
}

/// Outcome of [`Session::retry_file_lock`].
#[derive(Debug, PartialEq, Eq)]
enum Relock {
    NotNeeded,
    Restored,
    Failed { first: bool },
}

const FILE_UNPROTECTED_NOTICE: &str = "The vault file is open in another program, so it is not \
    protected against outside changes right now. Argus keeps trying.";

/// Protect the vault file again if a save left it unprotected, and say so once if it cannot.
/// Called a few times a second while the vault is unlocked.
fn keep_file_protected(ui: &MainWindow) {
    if with_session(Session::retry_file_lock) == Some(Relock::Failed { first: true }) {
        ui.set_status(FILE_UNPROTECTED_NOTICE.into());
    }
}

/// The copy Argus last put on the clipboard (if still pending) and the timer that clears it.
struct ClipboardState {
    ticket: Option<ClipboardTicket>,
    timer: Timer,
}

thread_local! {
    static SESSION: RefCell<Option<Session>> = const { RefCell::new(None) };
    static CLIPBOARD: RefCell<ClipboardState> =
        RefCell::new(ClipboardState { ticket: None, timer: Timer::default() });
}

static NEXT_SESSION_ID: AtomicU64 = AtomicU64::new(1);

/// Delay before retrying a clear that failed because the clipboard was busy.
const CLEAR_RETRY_SECS: u64 = 2;

fn with_session<R>(f: impl FnOnce(&mut Session) -> R) -> Option<R> {
    SESSION.with(|s| s.borrow_mut().as_mut().map(f))
}

/// `true` while a background re-key owns the vault file.
fn is_rekeying() -> bool {
    with_session(|s| s.rekeying).unwrap_or(false)
}

const REKEY_BUSY: &str = "Wait for the master password change to finish.";

fn user_message(err: &Error) -> String {
    if err.is_unlock_failure() {
        "Wrong password or keyfile, or the file is not a valid vault.".to_owned()
    } else {
        err.to_string()
    }
}

/// Memory that can be used right now without paging (`None` if Windows will not say).
fn usable_memory() -> Option<u64> {
    argus_platform::memory::status().ok().map(|s| s.usable())
}

/// Argon2id costs for a vault created (or re-keyed) on this machine: the largest memory size that
/// fits a quarter of the free memory and about 1.5 s, never below [`KdfParams::DEFAULT`] unless the
/// machine is short of memory (then `reduced` is set). Slow: worker thread only.
fn kdf_for_this_machine() -> Calibration {
    calibrate::for_this_machine(usable_memory())
        .unwrap_or(Calibration { params: KdfParams::DEFAULT, reduced: false })
}

/// Refuse to start a key derivation the machine cannot hold. Argon2 asks for all its memory at
/// once and this build aborts on allocation failure, so without this check a vault made on a big
/// machine would close the whole app, silently, on a small one.
fn ensure_memory_for(params: &KdfParams) -> Result<(), String> {
    const MIB: u64 = 1024 * 1024;
    let Some(free) = usable_memory() else { return Ok(()) };
    let need = calibrate::required_free_memory(params);
    if free >= need {
        return Ok(());
    }
    Err(format!(
        "This vault needs about {} MiB of free memory to open, and only {} MiB is free right now. \
         Close other programs and try again.",
        need.div_ceil(MIB),
        free / MIB
    ))
}

/// [`ensure_memory_for`] for the vault file at `path`. A file whose header cannot be read passes:
/// the real error comes from opening it.
fn ensure_memory_for_file(path: &Path) -> Result<(), String> {
    match UnlockedVault::peek_kdf_params(path) {
        Ok(params) => ensure_memory_for(&params),
        Err(_) => Ok(()),
    }
}

/// Open or create the vault. The `bool` is `true` when a new vault had to be created with reduced
/// strength because the machine is short of free memory.
fn open_or_create(
    path: &Path,
    keyfile: Option<&Path>,
    password: Zeroizing<String>,
    create: bool,
) -> Result<(UnlockedVault, bool), String> {
    let creds = match keyfile {
        Some(k) => Credentials::with_keyfile(password, k),
        None => Ok(Credentials::new(password)),
    }
    .map_err(|e| user_message(&e))?;
    if create {
        let calibration = kdf_for_this_machine();
        UnlockedVault::create(path, &creds, calibration.params)
            .map(|vault| (vault, calibration.reduced))
            .map_err(|e| user_message(&e))
    } else {
        ensure_memory_for_file(path)?;
        UnlockedVault::open(path, &creds).map(|vault| (vault, false)).map_err(|e| user_message(&e))
    }
}

