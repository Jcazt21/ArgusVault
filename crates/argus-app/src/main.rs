/// Lock because of a reason the user should be told about (inactivity, minimize, Windows lock).
fn lock_with_notice(ui: &MainWindow, notice: &str) {
    lock(ui);
    ui.set_notice(notice.into());
    ui.window().request_redraw();
}

thread_local! {
    static WAS_MINIMIZED: Cell<bool> = const { Cell::new(false) };
}

/// Make the window draw a new frame. `request_redraw` alone is not enough after a restore from
/// minimized (measured: the old frame stayed), but a real size change reconfigures the drawing
/// surface, so grow the window by one pixel and put it back right after.
fn force_repaint(ui: &MainWindow) {
    let window = ui.window();
    let size = window.size();
    window.set_size(slint::PhysicalSize::new(size.width + 1, size.height));
    let weak = ui.as_weak();
    Timer::single_shot(Duration::from_millis(30), move || {
        if let Some(ui) = weak.upgrade() {
            ui.window().set_size(size);
        }
    });
}

/// Debug builds only: `ARGUS_AUTOLOCK_SECS` replaces the vault's auto-lock time (which cannot go
/// below 30 s) so inactivity locking can be tested quickly. Always `None` in release builds.
fn debug_auto_lock_secs() -> Option<u32> {
    static OVERRIDE: OnceLock<Option<u32>> = OnceLock::new();
    *OVERRIDE.get_or_init(|| {
        if cfg!(debug_assertions) {
            std::env::var("ARGUS_AUTOLOCK_SECS").ok()?.parse().ok()
        } else {
            None
        }
    })
}

/// Lock when the window is minimized or the user has been away longer than the vault's
/// auto-lock time. Polled a few times a second.
fn check_auto_lock(ui: &MainWindow) {
    let minimized = ui.window().is_minimized();
    // Slint does not repaint a minimized window when it is restored (measured), so the last frame
    // drawn before the vault locked would stay on screen, vault contents included, until something
    // forced a redraw. Ask for a fresh frame the moment the window comes back.
    if WAS_MINIMIZED.replace(minimized) && !minimized {
        force_repaint(ui);
    }
    if !ui.get_unlocked() {
        return;
    }
    keep_file_protected(ui);
    let Some((auto_lock_secs, lock_on_minimize)) = with_session(|s| {
        (s.vault.vault.settings.auto_lock_secs, s.vault.vault.settings.lock_on_minimize)
    }) else {
        return;
    };
    let auto_lock_secs = debug_auto_lock_secs().unwrap_or(auto_lock_secs);
    if lock_on_minimize && minimized {
        lock_with_notice(ui, "Locked because the window was minimized.");
    } else if idle::idle_duration()
        .is_ok_and(|d| d >= Duration::from_secs(u64::from(auto_lock_secs)))
    {
        lock_with_notice(ui, "Locked after a period of inactivity.");
    }
}

/// How often, and for how long, to wait for Slint to create the native window.
const PROTECT_POLL: Duration = Duration::from_millis(50);
const PROTECT_MAX_ATTEMPTS: u32 = 100;

thread_local! {
    static PROTECT_TIMER: Timer = Timer::default();
}

const CAPTURE_ON: &str =
    "Screen-capture protection is on: this window is hidden from screenshots and recordings.";
const CAPTURE_MONITOR_ONLY: &str = "Screen-capture protection is partial (older Windows): the \
    window appears black in screenshots and recordings but is visible on screen.";
const CAPTURE_FAILED: &str = "Screen-capture protection could not be enabled.";

/// Shield the native window from capture. `None` while the window does not exist yet: Slint only
/// creates it once the event loop is running, not when `show()` returns.
fn try_protect_window(ui: &MainWindow) -> Option<Result<CaptureProtection, PlatformError>> {
    native_hwnd(ui).map(window::protect_from_capture)
}

/// Keep the window out of screenshots and recordings. Release builds always do this; debug
/// builds can opt out with `ARGUS_ALLOW_CAPTURE` so the UI can be driven by screenshot tooling.
///
/// The window can be visible for a few milliseconds before the protection lands (it only shows
/// the unlock screen at that point, never vault contents). The outcome — including failure — is
/// shown on the unlock screen and in the settings rather than ignored.
fn protect_window_when_ready(ui: &MainWindow) {
    if cfg!(debug_assertions) && std::env::var_os("ARGUS_ALLOW_CAPTURE").is_some() {
        ui.set_notice("Debug build: screen-capture protection is off.".into());
        ui.set_capture_status("Screen-capture protection is off (debug build).".into());
        ui.set_capture_ok(false);
        return;
    }
    ui.set_capture_status("Enabling screen-capture protection…".into());
    ui.set_capture_ok(true);
    let weak = ui.as_weak();
    let mut attempts = 0u32;
    PROTECT_TIMER.with(|timer| {
        timer.start(TimerMode::Repeated, PROTECT_POLL, move || {
            attempts += 1;
            let Some(ui) = weak.upgrade() else {
                PROTECT_TIMER.with(Timer::stop);
                return;
            };
            let fail = |ui: &MainWindow| {
                PROTECT_TIMER.with(Timer::stop);
                ui.set_notice(CAPTURE_FAILED.into());
                ui.set_capture_status(CAPTURE_FAILED.into());
                ui.set_capture_ok(false);
            };
            match try_protect_window(&ui) {
                Some(Ok(mode)) => {
                    PROTECT_TIMER.with(Timer::stop);
                    ui.set_capture_ok(true);
                    ui.set_capture_status(
                        match mode {
                            CaptureProtection::ExcludedFromCapture => CAPTURE_ON,
                            CaptureProtection::MonitorOnly => CAPTURE_MONITOR_ONLY,
                        }
                        .into(),
                    );
                }
                Some(Err(_)) => fail(&ui),
                None if attempts >= PROTECT_MAX_ATTEMPTS => fail(&ui),
                None => {}
            }
        });
    });
}

/// Lock when Windows locks the session or goes to sleep. The returned watcher must be kept alive.
fn watch_session(ui: &MainWindow) -> Option<SessionWatcher> {
    let weak = ui.as_weak();
    let watcher = SessionWatcher::start(move |event| {
        let weak = weak.clone();
        // Runs on the watcher thread: only hand the event to the UI thread.
        let _ = slint::invoke_from_event_loop(move || {
            if let Some(ui) = weak.upgrade() {
                lock_with_notice(
                    &ui,
                    match event {
                        SessionEvent::Locked => "Locked because Windows was locked.",
                        SessionEvent::Suspending => "Locked because the computer went to sleep.",
                    },
                );
            }
        });
    });
    if watcher.is_err() {
        ui.set_notice("Could not watch for Windows lock or sleep; lock the vault manually.".into());
    }
    watcher.ok()
}

fn open_message(err: PlatformError) -> String {
    match err {
        PlatformError::AlreadyOpen => {
            "This vault is already open in another Argus Vault window.".to_owned()
        }
        PlatformError::InUse => "This vault file is in use by another program.".to_owned(),
        _ => "Could not check whether this vault is open elsewhere.".to_owned(),
    }
}

/// Lock: drop the session (wiping the key and entries) and reset the UI.
fn lock(ui: &MainWindow) {
    ui.set_notice(SharedString::new());
    clear_now(&ui.as_weak());
    ui.set_status(SharedString::new());
    SESSION.with(|s| *s.borrow_mut() = None);
    ui.set_entries(ModelRc::new(VecModel::from(Vec::<EntryRow>::new())));
    vault_view::clear_detail(ui);
    vault_view::clear_form(ui);
    panes::clear_credential_fields(ui);
    panes::clear_generator(ui);
    ui.set_pane(0);
    ui.set_filter(0);
    ui.set_import_notice(SharedString::new());
    ui.set_error(SharedString::new());
    ui.set_unlocked(false);
}

// ------------------------------------------------------------ unlock screen

fn on_submit(
    ui: &MainWindow,
    path: &str,
    keyfile: &str,
    password: &str,
    confirm: &str,
    create: bool,
) {
    let password = Zeroizing::new(password.to_owned());
    let confirm = Zeroizing::new(confirm.to_owned());
    // Do not keep the master password in the text fields.
    ui.set_password(SharedString::new());
    ui.set_confirm_password(SharedString::new());
    ui.set_strength_score(0);
    ui.set_strength_label(SharedString::new());

    if path.trim().is_empty() {
        ui.set_error("Enter the path of the vault file.".into());
        return;
    }
    if create && password.as_str() != confirm.as_str() {
        ui.set_error("The two passwords do not match.".into());
        return;
    }
    ui.set_error(SharedString::new());
    ui.set_notice(SharedString::new());
    ui.set_busy(true);

    let path = path.trim().to_owned();
    let keyfile = keyfile.trim().to_owned();
    let weak = ui.as_weak();
    std::thread::spawn(move || {
        let keyfile_arg = (!keyfile.is_empty()).then_some(keyfile.clone());
        // Claim the vault first: if another window has it, fail before doing the slow KDF.
        let result = VaultLock::acquire(Path::new(&path)).map_err(open_message).and_then(|lock| {
            let (vault, reduced) = open_or_create(
                Path::new(&path),
                keyfile_arg.as_deref().map(Path::new),
                password,
                create,
            )?;
            let file_lock = ExclusiveFileLock::acquire(vault.path()).map_err(open_message)?;
            Ok((vault, lock, file_lock, reduced))
        });
        // If the window is gone the result (and its key) is simply dropped.
        let _ = slint::invoke_from_event_loop(move || {
            if let Some(ui) = weak.upgrade() {
                finish_unlock(&ui, result, keyfile);
            }
        });
    });
}

/// Shown after creating a vault on a machine with little free memory.
const REDUCED_STRENGTH_NOTICE: &str = "This computer has little free memory, so the vault was \
    created with weaker key protection. Change the master password later, on a machine with more \
    free memory, to strengthen it.";

fn finish_unlock(
    ui: &MainWindow,
    result: Result<(UnlockedVault, VaultLock, ExclusiveFileLock, bool), String>,
    keyfile: String,
) {
    ui.set_busy(false);
    match result {
        Ok((vault, instance, file_lock, reduced)) => {
            SESSION.with(|s| {
                *s.borrow_mut() = Some(Session {
                    id: NEXT_SESSION_ID.fetch_add(1, Ordering::Relaxed),
                    vault,
                    _instance: instance,
                    file_lock,
                    lock_warned: false,
                    keyfile,
                    shown: Vec::new(),
                    selected: None,
                    editing: None,
                    query: String::new(),
                    filter: None,
                    rekeying: false,
                });
            });
            ui.set_creating(false);
            ui.set_filter(0);
            ui.set_pane(0);
            vault_view::refresh_list(ui);
            ui.set_unlocked(true);
            if reduced {
                ui.set_status(REDUCED_STRENGTH_NOTICE.into());
            }
        }
        Err(message) => ui.set_error(message.into()),
    }
}

fn on_password_edited(ui: &MainWindow, password: &str) {
    let level = strength::evaluate(password);
    ui.set_strength_score(i32::from(level.score()));
    ui.set_strength_label(level.label().into());
}

fn on_browse_vault(ui: &MainWindow) {
    match pick_file(ui, Pick::Vault, ui.get_creating()) {
        Ok(Some(path)) => ui.set_vault_path(path.to_string_lossy().as_ref().into()),
        Ok(None) => {}
        Err(_) => ui.set_error("Could not open the file dialog.".into()),
    }
}

fn on_browse_keyfile(ui: &MainWindow) {
    match pick_file(ui, Pick::Keyfile, false) {
        Ok(Some(path)) => ui.set_keyfile_path(path.to_string_lossy().as_ref().into()),
        Ok(None) => {}
        Err(_) => ui.set_error("Could not open the file dialog.".into()),
    }
}

/// Ask where to put a brand-new keyfile and create it there. Used from the unlock screen (the
/// result is the keyfile for the vault being created) and from the settings (the new keyfile).
/// Never overwrites: an existing file is an error, not a keyfile to replace.
fn on_new_keyfile(ui: &MainWindow) {
    let in_vault = ui.get_unlocked();
    let report = |ui: &MainWindow, message: &str| {
        if in_vault {
            ui.set_settings_error(message.into());
        } else {
            ui.set_error(message.into());
        }
    };
    let path = match pick_file(ui, Pick::Keyfile, true) {
        Ok(Some(path)) => path,
        Ok(None) => return,
        Err(_) => return report(ui, "Could not open the file dialog."),
    };
    match argus_core::keyfile::generate(&path) {
        Ok(()) => {
            let shown: SharedString = path.to_string_lossy().as_ref().into();
            if in_vault {
                ui.set_cred_new_keyfile(shown);
                ui.set_settings_error(SharedString::new());
            } else {
                ui.set_keyfile_path(shown);
                ui.set_error(SharedString::new());
            }
        }
        Err(Error::Io(_)) => {
            report(ui, "Could not create the keyfile (does the file already exist?).");
        }
        Err(e) => report(ui, &user_message(&e)),
    }
}

fn main() -> Result<(), slint::PlatformError> {
    let ui = MainWindow::new()?;

    macro_rules! wire {
        ($register:ident, |$ui:ident $(, $arg:ident)*| $body:expr) => {{
            let weak = ui.as_weak();
            ui.$register(move |$($arg),*| {
                if let Some($ui) = weak.upgrade() {
                    $body;
                }
            });
        }};
    }

    // Unlock screen.
    wire!(on_submit, |ui, path, keyfile, password, confirm, create| on_submit(
        &ui, &path, &keyfile, &password, &confirm, create
    ));
    wire!(on_password_edited, |ui, password| on_password_edited(&ui, &password));
    wire!(on_browse_vault, |ui| on_browse_vault(&ui));
    wire!(on_browse_keyfile, |ui| on_browse_keyfile(&ui));
    wire!(on_new_keyfile, |ui| on_new_keyfile(&ui));
    wire!(on_lock, |ui| lock(&ui));

    // List and detail.
    wire!(on_search_edited, |ui, query| {
        with_session(|s| query.trim().clone_into(&mut s.query));
        vault_view::refresh_list(&ui);
    });
    wire!(on_set_filter, |ui, which| vault_view::set_filter(&ui, which));
    wire!(on_select, |ui, row| vault_view::on_select_clicked(&ui, row));
    wire!(on_toggle_reveal, |ui| vault_view::toggle_reveal(&ui));
    wire!(on_toggle_notes, |ui| vault_view::toggle_notes(&ui));
    wire!(on_copy_password, |ui| vault_view::copy_selected(&ui, vault_view::CopyField::Password));
    wire!(on_copy_username, |ui| vault_view::copy_selected(&ui, vault_view::CopyField::Username));
    wire!(on_copy_host, |ui| vault_view::copy_selected(&ui, vault_view::CopyField::Host));
    wire!(on_copy_row_password, |ui, row| vault_view::copy_row_password(&ui, row));

    // Editor.
    wire!(on_new_entry, |ui| vault_view::new_entry(&ui));
    wire!(on_edit_selected, |ui| vault_view::edit_selected(&ui));
    wire!(on_save_entry, |ui| vault_view::save_entry(&ui));
    wire!(on_cancel_form, |ui| vault_view::cancel_form(&ui));
    wire!(on_delete_selected, |ui| vault_view::delete_selected(&ui));
    wire!(on_import_file, |ui| vault_view::import_file(&ui));
    wire!(on_dismiss_import, |ui| ui.set_import_notice(SharedString::new()));

    // Settings and generator.
    wire!(on_open_settings, |ui| panes::open_settings(&ui));
    wire!(on_save_settings, |ui| panes::save_settings(&ui));
    wire!(on_change_credentials, |ui| panes::change_credentials(&ui));
    wire!(on_browse_cred_keyfile, |ui, which| panes::browse_cred_keyfile(&ui, which));
    wire!(on_open_generator, |ui, for_form| panes::open_generator(&ui, for_form));
    wire!(on_regenerate, |ui| panes::regenerate(&ui));
    wire!(on_use_generated, |ui| panes::use_generated(&ui));
    wire!(on_copy_generated, |ui| panes::copy_generated(&ui));
    wire!(on_close_generator, |ui| panes::close_generator(&ui));

    // Best effort: keep the heap out of Windows crash reports.
    let _ = process::exclude_heap_from_error_reports();

    // The native window only exists once the event loop runs, so protection is applied from a
    // timer as soon as it appears.
    protect_window_when_ready(&ui);
    let _session_watcher = watch_session(&ui);
    let auto_lock_poll = Timer::default();
    auto_lock_poll.start(TimerMode::Repeated, Duration::from_millis(250), {
        let weak = ui.as_weak();
        move || {
            if let Some(ui) = weak.upgrade() {
                check_auto_lock(&ui);
            }
        }
    });

    ui.run()?;
    // Do not leave a copied secret behind when the window is closed.
    clear_now(&ui.as_weak());
    // Closing the window drops the session and wipes the key.
    SESSION.with(|s| *s.borrow_mut() = None);
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::fs::OpenOptions;

    use argus_core::Entry;

    use super::*;

    /// A session over a fresh vault in its own temporary folder (cheap KDF costs).
    fn session_in_temp_dir(tag: &str) -> (Session, std::path::PathBuf) {
        let dir = std::env::temp_dir().join(format!("argus-session-{tag}-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("v.argus");
        let creds = Credentials::new(Zeroizing::new("correct horse battery".to_owned()));
        let vault = UnlockedVault::create(&path, &creds, KdfParams::MIN).unwrap();
        let session = Session {
            id: 1,
            vault,
            _instance: VaultLock::acquire(&path).unwrap(),
            file_lock: ExclusiveFileLock::acquire(&path).unwrap(),
            lock_warned: false,
            keyfile: String::new(),
            shown: Vec::new(),
            selected: None,
            editing: None,
            query: String::new(),
            filter: None,
            rekeying: false,
        };
        (session, dir)
    }

    #[test]
    fn a_save_leaves_the_file_protected_and_still_readable() {
        let (mut s, dir) = session_in_temp_dir("save");
        let path = s.vault.path().to_path_buf();
        s.vault.vault.upsert(Entry::new("Mail").unwrap()).unwrap();
        s.save().unwrap();

        assert!(s.file_lock.is_locked());
        assert!(OpenOptions::new().write(true).open(&path).is_err(), "writers are kept out");
        assert!(std::fs::read(&path).is_ok(), "readers (sync, backup) are not");
        // The data really is on disk.
        let creds = Credentials::new(Zeroizing::new("correct horse battery".to_owned()));
        assert_eq!(UnlockedVault::open(&path, &creds).unwrap().vault.entries.len(), 1);
        drop(s);
        let _ = std::fs::remove_dir_all(dir);
    }

    /// The bug this guards against: another program grabbing the file between the release and
    /// the re-lock of a save must not make the save look failed (callers roll memory back on
    /// `Err`, which would leave memory and disk different).
    #[test]
    fn a_lost_lock_after_a_save_is_retried_and_reported_once() {
        let (mut s, dir) = session_in_temp_dir("retry");
        let path = s.vault.path().to_path_buf();

        s.file_lock.release();
        let writer = OpenOptions::new().write(true).open(&path).unwrap();
        assert_eq!(s.retry_file_lock(), Relock::Failed { first: true });
        assert_eq!(s.retry_file_lock(), Relock::Failed { first: false }, "tell the user once");
        assert!(!s.file_lock.is_locked());

        drop(writer);
        assert_eq!(s.retry_file_lock(), Relock::Restored);
        assert!(s.file_lock.is_locked() && !s.lock_warned);
        assert_eq!(s.retry_file_lock(), Relock::NotNeeded);

        // A later failure is a new episode and is reported again.
        s.file_lock.release();
        let writer = OpenOptions::new().write(true).open(&path).unwrap();
        assert_eq!(s.retry_file_lock(), Relock::Failed { first: true });
        drop(writer);
        drop(s);
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn the_lock_is_left_alone_while_a_rekey_owns_the_file() {
        let (mut s, dir) = session_in_temp_dir("rekey");
        s.file_lock.release();
        s.rekeying = true;
        assert_eq!(s.retry_file_lock(), Relock::NotNeeded);
        assert!(!s.file_lock.is_locked(), "must stay released until the re-key ends");
        s.rekeying = false;
        assert_eq!(s.retry_file_lock(), Relock::Restored);
        drop(s);
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn saving_with_the_lock_already_lost_still_works_and_restores_it() {
        let (mut s, dir) = session_in_temp_dir("lost");
        s.file_lock.release();
        s.vault.vault.upsert(Entry::new("Bank").unwrap()).unwrap();
        s.save().unwrap();
        assert!(s.file_lock.is_locked());
        drop(s);
        let _ = std::fs::remove_dir_all(dir);
    }

    /// Real Argon2id at the calibrated size (about 1.5 s), so opt-in:
    /// `cargo test -p argus-app --release create_then_open -- --ignored --nocapture`.
    #[test]
    #[ignore = "slow: runs real Argon2id at the calibrated size"]
    #[allow(clippy::print_stdout)]
    fn create_then_open_with_calibrated_costs() {
        let dir = std::env::temp_dir().join(format!("argus-app-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("v.argus");
        let pw = || Zeroizing::new("correct horse battery".to_owned());

        let (vault, reduced) = open_or_create(&path, None, pw(), true).unwrap();
        vault.lock();
        let params = UnlockedVault::peek_kdf_params(&path).unwrap();
        println!("memory now: {:?}", argus_platform::memory::status().unwrap());
        println!("created with {params:?}, reduced = {reduced}");
        assert!(params.m_kib >= KdfParams::MIN.m_kib && params.validate().is_ok());
        assert!(
            ensure_memory_for(&params).is_ok(),
            "this machine must be able to open its own vault"
        );

        let start = std::time::Instant::now();
        open_or_create(&path, None, pw(), false).unwrap();
        println!("reopened in {:?}", start.elapsed());

        // A vault needing far more memory than exists is refused with a message, not attempted.
        let huge = KdfParams { m_kib: 2 * 1024 * 1024, ..KdfParams::DEFAULT };
        let total = argus_platform::memory::status().unwrap().total;
        if calibrate::required_free_memory(&huge) > total {
            assert!(ensure_memory_for(&huge).unwrap_err().contains("free memory"));
        }
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
